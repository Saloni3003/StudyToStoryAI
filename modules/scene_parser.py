import re


def parse_scenes(story):
    """
    Parse the educational storyboard generated by Qwen.

    Expected format:

    TITLE:
    ...

    SCENE 1:
    Narration: ...
    Visual: ...
    Animation: ...
    Technical Concept: ...
    Transition: ...

    SCENE 2:
    ...
    """

    # ========================================================
    # CLEAN MARKDOWN FORMATTING
    # ========================================================

    story = story.replace("**", "")
    story = story.replace("```text", "")
    story = story.replace("```", "")

    story = story.strip()

    # ========================================================
    # EXTRACT TITLE
    # ========================================================

    title_match = re.search(
        r"TITLE\s*:\s*(.*?)(?=\n\s*SCENE\s+1\s*:)",
        story,
        re.DOTALL | re.IGNORECASE
    )

    if title_match:
        title = title_match.group(1).strip()
    else:
        title = "StudyToStory AI"

    # ========================================================
    # EXTRACT SCENES
    # ========================================================

    scene_pattern = re.compile(
        r"SCENE\s+(\d+)\s*:\s*"
        r"\n?\s*"
        r"Narration\s*:\s*(.*?)"
        r"\n\s*Visual\s*:\s*(.*?)"
        r"\n\s*Animation\s*:\s*(.*?)"
        r"\n\s*Technical\s+Concept\s*:\s*(.*?)"
        r"\n\s*Transition\s*:\s*(.*?)"
        r"(?=\n\s*SCENE\s+\d+\s*:|\Z)",
        re.DOTALL | re.IGNORECASE
    )

    matches = scene_pattern.findall(story)

    scenes = []

    for match in matches:

        (
            number,
            narration,
            visual,
            animation,
            technical_concept,
            transition
        ) = match

        scenes.append({
            "scene_number": int(number.strip()),
            "narration": narration.strip(),
            "visual": visual.strip(),
            "animation": animation.strip(),
            "technical_concept": technical_concept.strip(),
            "transition": transition.strip()
        })

    return {
        "title": title,
        "scenes": scenes
    }