import os
import math

from PIL import Image, ImageDraw, ImageFont

from moviepy import (
    ImageClip,
    AudioFileClip,
    CompositeVideoClip,
    concatenate_videoclips
)


# ==========================================================
# VIDEO SETTINGS
# ==========================================================

VIDEO_WIDTH = 720
VIDEO_HEIGHT = 720

FPS = 24

BACKGROUND_COLOR = (10, 10, 18)


# ==========================================================
# FONT
# ==========================================================

def get_font(size):

    possible_fonts = [
        "/System/Library/Fonts/Supplemental/Arial.ttf",
        "/System/Library/Fonts/Supplemental/Helvetica.ttf",
        "/Library/Fonts/Arial.ttf"
    ]

    for font_path in possible_fonts:

        if os.path.exists(font_path):

            return ImageFont.truetype(
                font_path,
                size
            )

    return ImageFont.load_default()


# ==========================================================
# CREATE TITLE CARD
# ==========================================================

def create_title_card(
    title,
    duration=3
):

    image = Image.new(
        "RGB",
        (VIDEO_WIDTH, VIDEO_HEIGHT),
        BACKGROUND_COLOR
    )

    draw = ImageDraw.Draw(image)

    title_font = get_font(52)
    subtitle_font = get_font(28)

    title_text = title

    # Wrap title if necessary.
    words = title_text.split()

    lines = []
    current_line = ""

    for word in words:

        test_line = (
            current_line + " " + word
        ).strip()

        bbox = draw.textbbox(
            (0, 0),
            test_line,
            font=title_font
        )

        if bbox[2] > VIDEO_WIDTH - 100:

            lines.append(
                current_line
            )

            current_line = word

        else:

            current_line = test_line

    if current_line:
        lines.append(
            current_line
        )

    total_height = (
        len(lines) * 65
    )

    y = (
        VIDEO_HEIGHT - total_height
    ) / 2 - 30

    for line in lines:

        bbox = draw.textbbox(
            (0, 0),
            line,
            font=title_font
        )

        text_width = (
            bbox[2] - bbox[0]
        )

        x = (
            VIDEO_WIDTH - text_width
        ) / 2

        draw.text(
            (x, y),
            line,
            font=title_font,
            fill="white"
        )

        y += 65

    subtitle = "Generated by StudyToStory AI"

    bbox = draw.textbbox(
        (0, 0),
        subtitle,
        font=subtitle_font
    )

    subtitle_width = (
        bbox[2] - bbox[0]
    )

    draw.text(
        (
            (VIDEO_WIDTH - subtitle_width) / 2,
            y + 30
        ),
        subtitle,
        font=subtitle_font,
        fill="white"
    )

    path = "output/title_card.png"

    os.makedirs(
        "output",
        exist_ok=True
    )

    image.save(path)

    return (
        ImageClip(path)
        .with_duration(duration)
    )


# ==========================================================
# RESIZE IMAGE TO VIDEO SIZE
# ==========================================================

def prepare_image(image_path):

    image = Image.open(
        image_path
    ).convert("RGB")

    image = image.resize(
        (
            VIDEO_WIDTH,
            VIDEO_HEIGHT
        ),
        Image.Resampling.LANCZOS
    )

    image.save(
        image_path
    )

    return image_path


# ==========================================================
# ANIMATED SCENE
# ==========================================================

def create_animated_scene(
    image_path,
    audio_path,
    scene_number
):

    image_path = prepare_image(
        image_path
    )

    audio = AudioFileClip(
        audio_path
    )

    duration = audio.duration

    base_clip = (
        ImageClip(image_path)
        .with_duration(duration)
    )

    # ------------------------------------------------------
    # DIFFERENT CAMERA MOTION FOR EACH SCENE
    # ------------------------------------------------------

    if scene_number % 3 == 1:

        # Slow zoom IN
        animated = base_clip.resized(
            lambda t:
            1.0 + 0.08 * (t / duration)
        )

    elif scene_number % 3 == 2:

        # Slow zoom OUT
        animated = base_clip.resized(
            lambda t:
            1.08 - 0.08 * (t / duration)
        )

    else:

        # Gentle scale movement
        animated = base_clip.resized(
            lambda t:
            1.03 + 0.03 *
            math.sin(
                math.pi * t / duration
            )
        )

    # Center the moving image.
    animated = animated.with_position(
        "center"
    )

    # ------------------------------------------------------
    # ATTACH NARRATION
    # ------------------------------------------------------

    animated = animated.with_audio(
        audio
    )

    return animated


# ==========================================================
# CREATE FINAL VIDEO
# ==========================================================

def create_final_video(
    image_paths,
    audio_paths,
    output_path,
    title="StudyToStory AI"
):

    clips = []

    # ------------------------------------------------------
    # TITLE
    # ------------------------------------------------------

    title_clip = create_title_card(
        title,
        duration=3
    )

    clips.append(
        title_clip
    )

    # ------------------------------------------------------
    # SCENES
    # ------------------------------------------------------

    for index, (
        image_path,
        audio_path
    ) in enumerate(
        zip(
            image_paths,
            audio_paths
        ),
        start=1
    ):

        scene = create_animated_scene(
            image_path,
            audio_path,
            index
        )

        clips.append(
            scene
        )

    # ------------------------------------------------------
    # FINAL VIDEO
    # ------------------------------------------------------

    final_clip = concatenate_videoclips(
        clips,
        method="compose"
    )

    final_clip.write_videofile(
        output_path,
        fps=FPS,
        codec="libx264",
        audio_codec="aac",
        preset="medium"
    )

    # ------------------------------------------------------
    # CLEANUP
    # ------------------------------------------------------

    final_clip.close()

    for clip in clips:

        try:
            clip.close()
        except:
            pass

    return output_path